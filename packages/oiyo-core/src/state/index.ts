import type { OiyoConfig } from '@oiyo/config'

import { existsSync, mkdirSync, readFileSync } from 'node:fs'

import * as path from 'pathe'

import { atomicWriteFile, generateHash } from '~/shared'

import { version as oiyoVersion } from '../../package.json'

export interface OiyoMetadata {
  hash: string;
  project: {
    rootDir: string;
  };
  versions: {
    oiyo: string;
  };
}

export class OiyoState {
  constructor(
    private readonly config: OiyoConfig,
    private readonly mode: string = 'development',
  ) {}

  get envMode() {
    return this.mode
  }

  get stateDir() {
    return path.resolve(this.config.rootDir!, '.oiyo')
  }

  get typesDir() {
    return path.resolve(this.stateDir, 'types')
  }

  get declarationEntryPath() {
    return path.resolve(this.stateDir, 'oiyo.d.ts')
  }

  get tsconfigPath() {
    return path.resolve(this.stateDir, 'tsconfig.json')
  }

  get metadataPath() {
    return path.resolve(this.stateDir, 'oiyo.json')
  }

  get declarationPaths() {
    return [
      this.declarationEntryPath,
      this.tsconfigPath,
      path.resolve(this.typesDir, 'layouts.d.ts'),
      path.resolve(this.typesDir, 'pages.d.ts'),
    ]
  }

  get srcDir() {
    return path.resolve(this.config.rootDir!, this.config.srcDir!)
  }

  private relativeToState(targetPath: string) {
    return path.relative(this.stateDir, targetPath)
  }

  private stringifyJson(content: Record<string, unknown>) {
    return `${JSON.stringify(content, null, 2)}\n`
  }

  private serializeMetadataInput() {
    return JSON.stringify({
      rootDir: path.normalize(this.config.rootDir || ''),
      srcDir: this.config.srcDir || '',
      dir: this.config.dir || {},
      exclude: this.config.exclude || [],
    })
  }

  generateMetadataHash() {
    return generateHash(`${oiyoVersion}:${this.serializeMetadataInput()}`, 16)
  }

  generateMetadata(): OiyoMetadata {
    return {
      hash: this.generateMetadataHash(),
      project: {
        rootDir: path.normalize(this.config.rootDir || ''),
      },
      versions: {
        oiyo: oiyoVersion,
      },
    }
  }

  readMetadata() {
    if (!existsSync(this.metadataPath)) {
      return null
    }

    try {
      return JSON.parse(readFileSync(this.metadataPath, 'utf-8')) as OiyoMetadata
    }
    catch {
      return null
    }
  }

  writeMetadata() {
    mkdirSync(this.stateDir, { recursive: true })
    const metadata = this.generateMetadata()
    atomicWriteFile(this.metadataPath, this.stringifyJson(metadata as any))
    return metadata
  }

  canReuseGeneratedState() {
    const metadata = this.readMetadata()

    if (!metadata) {
      return false
    }

    if (metadata.project.rootDir !== path.normalize(this.config.rootDir || '')) {
      return false
    }

    if (metadata.versions.oiyo !== oiyoVersion) {
      return false
    }

    if (metadata.hash !== this.generateMetadataHash()) {
      return false
    }

    return this.declarationPaths.every(filePath => existsSync(filePath))
  }

  generateDeclarationEntry() {
    const lines = [
      '// Generated by oiyo',
      '',
      '/// <reference types="@dcloudio/types" />',
      '/// <reference types="@uni-helper/uni-types" />',
      '/// <reference path="./types/layouts.d.ts" />',
      '/// <reference path="./types/pages.d.ts" />',
      '',
      'export {}',
      '',
    ]

    return lines.join('\n')
  }

  generateTsconfig() {
    const rootRelative = this.relativeToState(this.config.rootDir!)
    const srcDirRelative = this.relativeToState(this.srcDir)
    const stateDirRelative = this.relativeToState(this.stateDir)

    return this.stringifyJson({
      compilerOptions: {
        paths: {
          '~/*': [path.join(srcDirRelative, '*')],
          '~~/*': [path.join(rootRelative, '*')],
          '@/*': [path.join(srcDirRelative, '*')],
          '@@/*': [path.join(rootRelative, '*')],
        },
        types: [],
        esModuleInterop: true,
        skipLibCheck: true,
        target: 'ES2018',
        allowJs: true,
        resolveJsonModule: true,
        moduleDetection: 'force',
        isolatedModules: true,
        verbatimModuleSyntax: true,
        allowArbitraryExtensions: true,
        strict: true,
        noUncheckedIndexedAccess: true,
        forceConsistentCasingInFileNames: true,
        noImplicitOverride: true,
        module: 'preserve',
        noEmit: true,
        lib: ['ESNext', 'DOM', 'DOM.Iterable'],
        moduleResolution: 'Bundler',
        useDefineForClassFields: true,
      },
      include: [
        path.join(stateDirRelative, 'oiyo.d.ts'),
        path.join(srcDirRelative, '**/*'),
        path.join(rootRelative, '*.d.ts'),
        path.join(rootRelative, 'types/**/*.d.ts'),
        path.join(rootRelative, 'oiyo.config.*'),
      ],
      exclude: [
        path.join(rootRelative, 'dist'),
        path.join(rootRelative, 'node_modules'),
      ],
    })
  }

  writeTsconfig() {
    mkdirSync(this.stateDir, { recursive: true })
    atomicWriteFile(this.tsconfigPath, this.generateTsconfig())

    return this.tsconfigPath
  }

  writeDeclarationEntry() {
    mkdirSync(this.stateDir, { recursive: true })
    atomicWriteFile(this.declarationEntryPath, this.generateDeclarationEntry())
    this.writeTsconfig()

    return this.declarationEntryPath
  }

  ensureDeclarationEntry() {
    if (!existsSync(this.tsconfigPath)) {
      this.writeTsconfig()
    }

    if (!existsSync(this.declarationEntryPath)) {
      return this.writeDeclarationEntry()
    }

    const currentContent = readFileSync(this.declarationEntryPath, 'utf-8')
    if (currentContent !== this.generateDeclarationEntry()) {
      return this.writeDeclarationEntry()
    }

    return this.declarationEntryPath
  }

  markGenerated() {
    return this.writeMetadata()
  }
}
