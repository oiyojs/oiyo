import type { ResolvedPagesJson, Route } from './types'

import * as path from 'pathe'

function normalizePageUrl(path: string) {
  const normalizedPath = path.startsWith('/') ? path : `/${path}`
  return `'${normalizedPath}'`
}

function resolveAllPagePaths(pagesJson: ResolvedPagesJson) {
  const allPagePaths = new Set<string>()

  for (const page of pagesJson.pages || []) {
    allPagePaths.add(normalizePageUrl(page.path))
  }

  for (const subPackage of pagesJson.subPackages || []) {
    for (const page of subPackage.pages || []) {
      allPagePaths.add(normalizePageUrl(path.join(subPackage.root, page.path)))
    }
  }

  return Array.from(allPagePaths).sort()
}

function resolveTabBarPaths(pagesJson: ResolvedPagesJson) {
  const tabPaths = new Set<string>()

  for (const item of pagesJson.tabBar?.list || []) {
    tabPaths.add(normalizePageUrl(item.pagePath))
  }

  return Array.from(tabPaths).sort()
}

function renderUrlUnion(paths: string[]) {
  return paths.length > 0 ? paths.join(' |\n       ') : 'string'
}

export function generatePagesJson(routes: Route[]): ResolvedPagesJson {
  const mainPackage: Route[] = []
  const subPackagesMap = new Map<string, Route[]>()

  routes.forEach((raw) => {
    if (raw.pageBelong === 'pages') {
      mainPackage.push(raw)
    }
    else {
      const subPages = subPackagesMap.get(raw.pageBelong) || []
      subPages.push(raw)
      subPackagesMap.set(raw.pageBelong, subPages)
    }
  })

  mainPackage.sort((a, b) => {
    const aIsHome = mainPackage.find(p => p.pagePath === a.pagePath)?.pageMeta?.type === 'home'
    const bIsHome = mainPackage.find(p => p.pagePath === b.pagePath)?.pageMeta?.type === 'home'

    if (aIsHome && !bIsHome) {
      return -1
    }
    if (!aIsHome && bIsHome) {
      return 1
    }
    return a.pagePath.localeCompare(b.pagePath)
  })

  const pagesJson: ResolvedPagesJson = {
    pages: mainPackage.map((route) => {
      const { pagePath: path, pageMeta } = route
      return { path, ...pageMeta }
    }),
  }

  if (subPackagesMap.size > 0) {
    const sortedEntries = Array.from(subPackagesMap.entries())
      .sort(([a], [b]) => a.localeCompare(b))

    pagesJson.subPackages = sortedEntries.map(([root, subPages]) => ({
      root,
      pages: subPages
        .sort((a, b) => a.pagePath.localeCompare(b.pagePath))
        .map((route) => {
          const path = route.pagePath
          const { tab, ...meta } = route.pageMeta || { tab: null }
          return { path, ...meta }
        }),
    }))
  }

  const tabs = mainPackage
    .filter(file => !!file.pageMeta?.tab)
    .map(route => ({
      pagePath: route.pagePath,
      ...route.pageMeta!.tab!,
    }))
    .sort((a, b) => a.index > b.index ? 1 : -1)

  if (tabs.length > 0) {
    pagesJson.tabBar = {
      list: tabs,
    }
  }

  return pagesJson
}

export function generatePagesDeclaration(pagesJson: ResolvedPagesJson) {
  const allPagePaths = resolveAllPagePaths(pagesJson)
  const tabPaths = resolveTabBarPaths(pagesJson)

  const lines = [
    '// Generated by oiyo(https://oiyo.js.org)',
    '/* eslint-disable */',
    '/* prettier-ignore */',
    '// @ts-nocheck',
    '',
    'import type { PageMeta } from \'@oiyojs/oiyo/global\'',
    '',
    'interface NavigateToOptions {',
    `  url: ${renderUrlUnion(allPagePaths)};`,
    '}',
    'interface RedirectToOptions extends NavigateToOptions {}',
    '',
    'interface SwitchTabOptions {',
    tabPaths.length > 0 ? `  url: ${tabPaths.join(' |\n       ')};` : '',
    '}',
    '',
    'type ReLaunchOptions = NavigateToOptions | SwitchTabOptions;',
    '',
    'declare global {',
    '  function definePageMeta(meta: PageMeta): void;',
    '',
    '  interface Uni {',
    '    navigateTo(options: UniNamespace.NavigateToOptions & NavigateToOptions): void;',
    '    redirectTo(options: UniNamespace.RedirectToOptions & RedirectToOptions): void;',
    '    switchTab(options: UniNamespace.SwitchTabOptions & SwitchTabOptions): void;',
    '    reLaunch(options: UniNamespace.ReLaunchOptions & ReLaunchOptions): void;',
    '  }',
    '}',
    '',
    'export {}',
    '',
  ]

  return lines.join('\n')
}
