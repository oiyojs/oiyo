import type { OiyoConfig } from '@oiyo/config'

import type { LayoutFile } from './types'
import type { Logger } from '~/logger'
import type { OiyoState } from '~/state'

import { mkdirSync } from 'node:fs'

import { generateInterfaceItemType } from '#/shared/generator/type'
import { DEFAULT_EXCLUDE } from '@oiyo/config'
import * as path from 'pathe'

import { atomicWriteFile, scanFiles } from '~/shared'

import { resolveLayoutComponentName, resolveLayoutUseName } from './resolver'

export class OiyoModLayout {
  private readonly config: OiyoConfig

  private readonly logger: Logger

  private readonly oiyoState: OiyoState

  layouts: Map<string, LayoutFile> = new Map()

  constructor(
    config: OiyoConfig,
    deps: {
      logger: Logger;
      oiyoState: OiyoState;
    },
  ) {
    this.config = config
    this.logger = deps.logger.withScope('LAYOUT')

    this.oiyoState = deps.oiyoState
  }

  private get srcDir() {
    return this.oiyoState.srcDir
  }

  private get layoutDir() {
    return path.resolve(this.srcDir, this.config.dir?.layouts || 'layouts')
  }

  get declarationDir() {
    return this.oiyoState.typesDir
  }

  get declarationFile() {
    return path.resolve(this.declarationDir, 'layouts.d.ts')
  }

  private toLayout(file: string): LayoutFile {
    const useName = resolveLayoutUseName(file, this.layoutDir)
    const componentName = resolveLayoutComponentName(useName)

    return {
      filePath: file,
      componentName,
      useName,
    }
  }

  private saveLayout(newLayout: LayoutFile) {
    if (this.layouts.has(newLayout.useName)) {
      return false
    }

    this.layouts.set(newLayout.useName, newLayout)
    return true
  }

  async scanLayouts() {
    this.logger.debug('参数扫描布局目录，共 1 个')

    const files = await scanFiles({
      dir: this.layoutDir,
      pattern: ['**/*.vue', '**/*.nvue'],
      ignore: [...DEFAULT_EXCLUDE, ...(this.config.exclude || [])],
    })

    files.forEach((file) => {
      const layout = this.toLayout(file)
      const isSave = this.saveLayout(layout)
      isSave && this.logger.debug(`通过“扫描模式”录入布局: ${layout.useName}`)
    })

    this.logger.debug(`通过扫描目录，共录入 ${this.layouts.size}个 布局`)

    return this.layouts
  }

  isLayout(file: string) {
    if (!file.endsWith('.vue') && !file.endsWith('.nvue')) {
      return false
    }

    const exclude = [...DEFAULT_EXCLUDE, ...(this.config.exclude || [])]
    if (exclude.some(pattern => path.matchesGlob(file, pattern))) {
      return false
    }

    return file.startsWith(`${this.layoutDir}/`)
  }

  enterLayout(file: string) {
    const layout = this.toLayout(file)

    const isSave = this.saveLayout(layout)

    isSave && this.logger.debug(`通过“主动模式”录入布局: ${layout.useName}`)

    return isSave
  }

  exitLayout(file: string) {
    const layout = Array.from(this.layouts.values()).find(layout => layout.filePath === file)
    if (!layout) {
      this.logger.debug(`无法脱离不存在的布局：${file}`)
      return false
    }

    const isDelete = this.layouts.delete(layout.useName)

    isDelete && this.logger.debug(`通过“主动模式”脱离布局: ${layout.useName}`)

    return isDelete
  }

  generateDeclaration() {
    const lines = [
      '// Generated by oiyo(https://oiyo.js.org)',
      '/* eslint-disable */',
      '/* prettier-ignore */',
      '// @ts-nocheck',
      'declare module \'@oiyojs/oiyo/global\' {',
      '  interface OiyoLayouts {',
      ...Array.from(this.layouts.values())
        .sort((a, b) => a.useName.localeCompare(b.useName))
        .map(({ useName, filePath }) => {
          return `    ${generateInterfaceItemType(filePath, `'${useName}'`, 'default', {
            baseDir: this.declarationDir,
          })}`
        }),
      '  }',
      '',
      '  type LayoutKey = keyof OiyoLayouts extends never ? string : keyof OiyoLayouts;',
      '',
      '  interface PageMeta {',
      '    layout?: LayoutKey | false;',
      '  }',
      '}',
      '',
      'export {}',
      '',
    ]

    return lines.join('\n')
  }

  writeDeclaration() {
    try {
      mkdirSync(this.declarationDir, { recursive: true })

      atomicWriteFile(this.declarationFile, this.generateDeclaration())

      this.oiyoState.ensureDeclarationEntry()

      this.logger.debug(`写入 layouts.d.ts 布局类型声明，共 ${this.layouts.size} 个页面`)

      return true
    }
    catch (error) {
      this.logger.error('无法写入 layouts.d.ts 布局类型声明，请检查目标文件权限和内容格式:', {
        error: error as Error,
      })

      return false
    }
  }
}
